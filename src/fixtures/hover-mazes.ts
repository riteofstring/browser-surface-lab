// Three mazes after Hover!'s castle, futuristic city and sewer. Tiles: #
// wall, . ground, = upper tier, > < v ^ ramps rising east, west, south and
// north. Things: P start, E blue seeker, G green hunter; pods j spring, w
// wall, c cloak, + green light, - red light, s shield, m map eraser, z slow
// drones, ? random; floor tiles u d l r (arrows that push that way), x
// (swirl, holds you) and f (sends a carried flag back to its stand). Flags
// are placed at random each round, as in the original.

interface MazeLook {
  accent: string;
  floor: [string, string];
  fog: string;
  label: string;
  sky: [string, string];
  top: [string, string];
  wall: [string, string, string];
}

export interface Maze {
  look: MazeLook;
  name: string;
  things: readonly string[];
  tiles: readonly string[];
}

